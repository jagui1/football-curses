/**
 * Pre-build: hashes WITCH_PASSWORD and ADMIN_PASSWORD with bcrypt (cost 12)
 * and writes src/app/auth/password-hashes.ts (gitignored).
 *
 * Usage: WITCH_PASSWORD=... ADMIN_PASSWORD=... node scripts/hash-passwords.mjs
 */
import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import bcrypt from 'bcryptjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../src/app/auth/password-hashes.ts');

const witch = process.env.WITCH_PASSWORD;
const admin = process.env.ADMIN_PASSWORD;

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

if (!witch || typeof witch !== 'string' || witch.length === 0) {
  fail(
    'hash-passwords: missing WITCH_PASSWORD. Set it in the environment (see .env.example).',
  );
}
if (!admin || typeof admin !== 'string' || admin.length === 0) {
  fail(
    'hash-passwords: missing ADMIN_PASSWORD. Set it in the environment (see .env.example).',
  );
}
if (witch === admin) {
  fail(
    'hash-passwords: WITCH_PASSWORD and ADMIN_PASSWORD must be different (plain-text equality check).',
  );
}

const rounds = 12;
const WITCH_HASH = bcrypt.hashSync(witch, rounds);
const ADMIN_HASH = bcrypt.hashSync(admin, rounds);

if (WITCH_HASH === ADMIN_HASH) {
  fail(
    'hash-passwords: hashed outputs collided (extremely unlikely). Use different passwords.',
  );
}

mkdirSync(dirname(outPath), { recursive: true });
const ts = `/* Generated by scripts/hash-passwords.mjs — do not edit by hand */
export const WITCH_HASH = ${JSON.stringify(WITCH_HASH)};
export const ADMIN_HASH = ${JSON.stringify(ADMIN_HASH)};
`;
writeFileSync(outPath, ts, 'utf8');
console.log(`Wrote ${outPath}`);
